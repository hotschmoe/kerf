#!/usr/bin/env python3
"""Generates engines/rust/kerf-verified/src (plain Rust, zero dependencies) from the Verus sources
in engines/rust/kerf-verified/proof/src.

The erasure itself is Verus's: the proof crate is compiled as ordinary Rust, where the `verus!`
macro (verus_builtin_macros) drops specs, proofs and ghost code, and rustc prints the expanded
crate (`-Zunpretty=expanded`). This script only removes what that leaves behind: vstd imports, empty
blocks where proof blocks and asserts were, empty spec-only modules, `#[doc = ...]` attributes
(back to `///`), then splits the crate into one file per module and runs rustfmt.

    erase.py            regenerate kerf-verified/src
    erase.py --check    regenerate into a temporary directory and fail if it differs
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE = os.path.normpath(os.path.join(HERE, "..", "kerf-verified"))
PROOF = os.path.join(CRATE, "proof")
TOOLCHAIN = "1.99.1"  # Verus's pinned toolchain: same rustc for verification and erasure
FMT_TOOLCHAIN = "stable"

HEADER = "// @generated by engines/rust/verus/erase.py from proof/src/{name}.rs. Do not edit.\n"


def expand():
    env = dict(os.environ, RUSTC_BOOTSTRAP="1")
    r = subprocess.run(
        ["cargo", f"+{TOOLCHAIN}", "rustc", "--release", "--lib", "-q", "--", "-Zunpretty=expanded"],
        cwd=PROOF, env=env, capture_output=True, text=True,
    )
    if r.returncode != 0:
        sys.exit(r.stderr)
    return r.stdout


def unescape(s):
    return re.sub(r"\\(.)", lambda m: {"n": "\n", "t": "\t"}.get(m.group(1), m.group(1)), s)


def doc_comments(text):
    def rep(m):
        indent, inner = m.group(1), unescape(m.group(2))
        return "\n".join(f"{indent}///{line}" for line in inner.split("\n"))
    return re.sub(r'^([ \t]*)#\[doc\s*=\s*"((?:[^"\\]|\\.)*)"\]', rep, text, flags=re.M)


def split_modules(text):
    """Top-level `pub mod name { ... }` blocks of the expanded crate, by name."""
    mods = {}
    for m in re.finditer(r"^(?:#\[path\s*=\s*\"[^\"]*\"\]\s*)?pub mod (\w+) \{\n(.*?)^\}\n", text, re.S | re.M):
        mods[m.group(1)] = m.group(2)
    return mods


def rustfmt(path):
    subprocess.run(["rustfmt", f"+{FMT_TOOLCHAIN}", "--edition", "2024", path], check=True)


def tidy(body):
    body = re.sub(r"^\s*use (vstd|verus_builtin|verus_builtin_macros)::[^;]*;\n", "", body, flags=re.M)
    body = re.sub(r"^\s*const _: \(\) = \(\);\n", "", body, flags=re.M)
    body = doc_comments(body)
    # spec-only inner modules erase to nothing
    for name in re.findall(r"^\s*pub mod (\w+) \{\s*\}\n", body, flags=re.M):
        body = re.sub(rf"^\s*pub mod {name} \{{\s*\}}\n", "", body, flags=re.M)
        body = re.sub(rf"^\s*pub use {name}::\*;\n", "", body, flags=re.M)
    return body


def strip_empty_blocks(path):
    for _ in range(4):
        rustfmt(path)
        src = open(path).read()
        out = re.sub(r"^[ \t]*\{\};?\n", "", src, flags=re.M)
        out = re.sub(r"\s*else \{\s*\}", "", out)
        open(path, "w").write(out)
        if out == src:
            break
    rustfmt(path)
    src = open(path).read()
    src = re.sub(r"^\}\n(?=(pub |fn |impl|struct |enum |///|#\[))", "}\n\n", src, flags=re.M)
    src = re.sub(r"^(use [^\n]*;\n)(?=(pub |fn |impl|struct |enum |///|#\[))", "\\1\n", src, flags=re.M)
    open(path, "w").write(src)


def generate(dest):
    text = expand()
    mods = split_modules(text)
    if not mods:
        sys.exit("erase.py: no modules found in the expanded crate")
    os.makedirs(dest, exist_ok=True)
    kept = []
    for name, body in mods.items():
        body = tidy(body)
        if not body.strip():
            continue
        path = os.path.join(dest, f"{name}.rs")
        with open(path, "w") as f:
            f.write(HEADER.format(name=name) + body)
        strip_empty_blocks(path)
        kept.append(name)
    lib = os.path.join(dest, "lib.rs")
    with open(lib, "w") as f:
        f.write("// @generated by engines/rust/verus/erase.py from proof/src/lib.rs. Do not edit.\n")
        f.write("//! Verified kernels for Kerf (see engines/rust/verus/VERUS.md for what is proven).\n")
        f.write("#![no_std]\n#![forbid(unsafe_code)]\nextern crate alloc;\n\n")
        for name in kept:
            f.write(f"pub mod {name};\n")
    rustfmt(lib)
    leftovers = []
    for name in kept + ["lib"]:
        src = open(os.path.join(dest, f"{name}.rs")).read()
        for word in ("vstd", "verus_builtin", "Ghost", "Tracked", "assume_new_fallback"):
            if re.search(rf"\b{word}\b", src):
                leftovers.append(f"{name}.rs: {word}")
    if leftovers:
        sys.exit("erase.py: erased code still references Verus items (ghost parameters in an exec signature?):\n  "
                 + "\n  ".join(leftovers))


def main():
    out = os.path.join(CRATE, "src")
    if "--check" in sys.argv:
        tmp = tempfile.mkdtemp()
        try:
            generate(tmp)
            r = subprocess.run(["diff", "-ru", out, tmp], capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit("erase.py --check: kerf-verified/src is stale; run engines/rust/verus/erase.py\n" + r.stdout)
            print("erase.py --check: kerf-verified/src matches proof/src")
        finally:
            shutil.rmtree(tmp)
    else:
        shutil.rmtree(out, ignore_errors=True)
        generate(out)
        print(f"erase.py: wrote {out}")


if __name__ == "__main__":
    main()

//! Compiles the embedded stroke font (spec/fonts/kerf-simplex.json, SPEC 15) into static glyph tables, so no call
//! parses it at run time. The JSON goes through the engine's own parser; every coordinate is a small integer, stored as
//! `i8` (exact as f64), and the build fails if a future font breaks that.

extern crate alloc;

#[allow(dead_code)]
#[path = "src/json.rs"]
mod json;
#[allow(dead_code)]
#[path = "src/math.rs"]
mod math;
#[allow(dead_code)]
#[path = "src/num.rs"]
mod num;
#[allow(dead_code)]
#[path = "src/sort.rs"]
mod sort;

use json::Value;
use std::fmt::Write;

type Strokes = Vec<Vec<(f64, f64)>>;

fn glyph(v: &Value) -> (f64, Strokes) {
    let adv = v.get("adv").and_then(Value::num).expect("font glyph without numeric adv");
    let strokes = v.get("strokes").and_then(Value::arr).expect("font glyph without strokes");
    let strokes = strokes
        .iter()
        .map(|s| {
            s.arr()
                .expect("font stroke is not an array")
                .iter()
                .map(|p| match p.arr().expect("font point is not an array") {
                    [x, y, ..] => (x.num().unwrap_or(0.0), y.num().unwrap_or(0.0)),
                    _ => panic!("font point needs two numbers"),
                })
                .collect()
        })
        .collect();
    (adv, strokes)
}

fn small_int(v: f64) -> i8 {
    assert!(v.fract() == 0.0 && (-128.0..=127.0).contains(&v), "font coordinate {v} is not an integer in i8 range");
    v as i8
}

fn emit(out: &mut String, (adv, strokes): &(f64, Strokes)) {
    write!(out, "Glyph {{ adv: {adv:?}, strokes: &[").unwrap();
    for s in strokes {
        out.push_str("&[");
        for &(x, y) in s {
            write!(out, "[{},{}],", small_int(x), small_int(y)).unwrap();
        }
        out.push_str("],");
    }
    out.push_str("] }");
}

fn main() {
    let path = "../../spec/fonts/kerf-simplex.json";
    println!("cargo::rerun-if-changed={path}");
    println!("cargo::rerun-if-changed=src/json.rs");
    let src = std::fs::read(path).expect("read the stroke font");
    let root = json::parse(&src).unwrap_or_else(|e| panic!("{path}: {} (line {})", e.msg, e.line));
    let cap = root.get("cap_height").and_then(Value::num).expect("font cap_height");
    let gl = root.get("glyphs").expect("font glyphs");
    let mut ascii: Vec<(f64, Strokes)> =
        (32..127u8).map(|ch| gl.get(core::str::from_utf8(&[ch]).unwrap()).map(glyph).unwrap_or_default()).collect();
    let question = ascii[usize::from(b'?' - 32)].clone();
    for slot in ascii.iter_mut().skip(1) {
        if slot.0 == 0.0 {
            *slot = question.clone();
        }
    }
    let line = |pts: &[(f64, f64)]| pts.to_vec();
    let extra = [
        ("EMDASH", (24.0, vec![line(&[(0.0, 8.0), (24.0, 8.0)])])),
        ("ENDASH", (20.0, vec![line(&[(0.0, 8.0), (18.0, 8.0)])])),
        (
            "PLUSMINUS",
            (
                20.0,
                vec![
                    line(&[(10.0, 17.0), (10.0, 5.0)]),
                    line(&[(4.0, 11.0), (16.0, 11.0)]),
                    line(&[(4.0, 0.0), (16.0, 0.0)]),
                ],
            ),
        ),
        ("DEGREE", (12.0, vec![])),
        ("TIMES", ascii[usize::from(b'X' - 32)].clone()),
    ];
    let mut out = String::from("// @generated by kerf-core/build.rs from spec/fonts/kerf-simplex.json\n");
    writeln!(out, "pub(crate) const CAP: f64 = {cap:?};").unwrap();
    out.push_str("pub(crate) static ASCII: [Glyph; 95] = [\n");
    for g in &ascii {
        emit(&mut out, g);
        out.push_str(",\n");
    }
    out.push_str("];\n");
    for (name, g) in &extra {
        write!(out, "pub(crate) static {name}: Glyph = ").unwrap();
        emit(&mut out, g);
        out.push_str(";\n");
    }
    let dst = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("font_data.rs");
    std::fs::write(dst, out).expect("write font_data.rs");
}
